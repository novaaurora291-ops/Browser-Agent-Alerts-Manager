"""Local mock of the Hark chat routes Team Dispatch uses (hark_api.py contract). 127.0.0.1 only, never hark.com.

Mock accounts sign in to mock Cent profiles: each managed profile tag has its own cookie jar, so an account switch
in the same Cent profile is sign_in(tag, other_user) - the profile's old session stops working at once, exactly like
signing out and in again in that browser. Replies are generated by the mock after `reply_delay` seconds, streaming
first, under the responseMessageId the sender chose."""
import copy
import hashlib
import json
import secrets
import threading
import time
import uuid
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import parse_qs, urlsplit

COOKIE = "hark_mock_session"
REQUIRED = ("timezone", "conversationId", "message", "idempotencyKey", "responseMessageId")
FAULTS = ("http500", "drop_ack", "hide_message", "wrong_ack_conversation")


def user_id_for(email):
    return "usr_" + hashlib.sha256((email or "").strip().lower().encode("utf-8")).hexdigest()[:12]


class MockHark:
    def __init__(self, reply_delay=1.0):
        self.lock = threading.RLock()
        self.accounts = {}   # user id -> {"id", "email"}
        self.sessions = {}   # session token -> user id
        self.jars = {}       # Cent profile tag -> its session token (that browser's cookie jar)
        self.projects = {}   # project id -> {"id", "projectId", "userId", "title", "messages": [...]}
        self.acks = {}       # (user id, idempotencyKey) -> acknowledgement (a repeated key never sends again)
        self.sends = []      # every request that stored a user message
        self.faults = []     # one-shot faults for the next send: [(kind, project id or "")]
        self.reply_delay = reply_delay
        self.server = None
        self.base_url = ""

    # ---------- accounts, projects, Cent profiles ----------
    def add_account(self, email):
        email = (email or "").strip().lower()
        uid = user_id_for(email)
        with self.lock:
            self.accounts.setdefault(uid, {"id": uid, "email": email})
        return uid

    def add_project(self, project_id, user_id, title=""):
        """Creates the project for user_id. Returns False when it already belongs to another account."""
        with self.lock:
            p = self.projects.setdefault(project_id, {"id": project_id, "projectId": project_id, "userId": user_id,
                                                      "title": title or "Project " + project_id[:8], "messages": []})
            return p["userId"] == user_id

    def set_owner(self, project_id, user_id):
        """Gives an existing project to another account (the team's worker account was changed)."""
        with self.lock:
            if user_id not in self.accounts:
                raise KeyError(user_id)
            self.projects[project_id]["userId"] = user_id

    def sign_in(self, tag, user_id):
        with self.lock:
            if user_id not in self.accounts:
                raise KeyError(user_id)
            self.sessions.pop(self.jars.get(tag), None)
            tok = secrets.token_urlsafe(24)
            self.sessions[tok] = user_id
            self.jars[tag] = tok

    def sign_out(self, tag):
        with self.lock:
            self.sessions.pop(self.jars.pop(tag, None), None)

    def signed_in(self, tag):
        with self.lock:
            uid = self.sessions.get(self.jars.get(tag))
            return dict(self.accounts[uid]) if uid in self.accounts else None

    def cookie_header(self, tag):
        """What that Cent profile's browser would send (only to this mock)."""
        with self.lock:
            tok = self.jars.get(tag)
        return {"Cookie": f"{COOKIE}={tok}"} if tok else {}

    def inject_fault(self, kind, project_id=""):
        if kind not in FAULTS:
            raise ValueError(kind)
        with self.lock:
            self.faults.append((kind, project_id))

    def inject_message(self, project_id, message):
        with self.lock:
            self.projects[project_id]["messages"].append(dict(message))

    def user_messages(self, project_id):
        with self.lock:
            return [dict(m) for m in self.projects.get(project_id, {}).get("messages", []) if m.get("role") == "user"]

    # ---------- the routes ----------
    def _user(self, headers):
        raw = headers.get("Cookie", "") or ""
        tok = next((c.split("=", 1)[1] for c in (x.strip() for x in raw.split(";")) if c.startswith(COOKIE + "=")), "")
        with self.lock:
            return self.sessions.get(tok)

    def handle(self, method, path, query, headers, body):
        uid = self._user(headers)
        if method == "GET" and path == "/api/auth/get-session":
            if not uid:
                return 401, {"error": "unauthorized"}
            with self.lock:
                a = self.accounts[uid]
            return 200, {"session": {"userId": uid}, "user": {"id": uid, "email": a["email"]}}
        if method == "GET" and path == "/api/conversations/main":
            if not uid:
                return 401, {"error": "unauthorized"}
            with self.lock:
                own = [copy.deepcopy(p) for p in self.projects.values() if p["userId"] == uid]
            return 200, {"timezone": (query.get("timezone") or [""])[0], "conversations": own}
        if method == "POST" and path == "/api/messages/send":
            if not uid:
                return 401, {"error": "unauthorized"}
            return self._send(uid, (query.get("cid") or [""])[0], body if isinstance(body, dict) else {})
        return 404, {"error": "not_found"}

    def _send(self, uid, cid, body):
        missing = [k for k in REQUIRED if not body.get(k)]
        if missing:
            return 400, {"error": "missing_" + "_".join(missing)}
        if body["conversationId"] != cid:
            return 400, {"error": "cid_mismatch"}
        if body.get("expectedUserId") and body["expectedUserId"] != uid:
            return 409, {"error": "user_mismatch"}       # the session changed account: Hark refuses the send
        with self.lock:
            p = self.projects.get(cid)
            if not p or p["userId"] != uid:
                return 404, {"error": "conversation_not_found"}
            key = (uid, body["idempotencyKey"])
            if key in self.acks:
                return 200, dict(self.acks[key], replayed=True)
            fault = next((f for f in self.faults if f[1] in ("", cid)), None)
            if fault:
                self.faults.remove(fault)
            kind = fault[0] if fault else ""
            if kind == "http500":
                return 500, {"error": "internal"}
            mid = "msg_" + uuid.uuid4().hex[:16]
            ack = {"messageId": mid, "conversationId": cid, "agentId": "agent_mock", "steered": False,
                   "redirected": False}
            self.acks[key] = ack
            if kind != "hide_message":
                rid = body["responseMessageId"]
                p["messages"].append({"id": mid, "role": "user", "content": body["message"], "userId": uid,
                                      "createdAt": time.time()})
                p["messages"].append({"id": rid, "role": "assistant", "content": "", "userId": uid,
                                      "isStreaming": True, "jobStatus": "running"})
                self.sends.append({"user": uid, "project": cid, "message_id": mid, "reply_id": rid, "t": time.time()})
                email = self.accounts[uid]["email"]
                final = f"MOCK-REPLY project={cid} account={email}: task received ({len(body['message'])} chars)"
                for frac, done in ((0.5, False), (1.0, True)):
                    t = threading.Timer(self.reply_delay * frac, self._reply, (cid, rid, final, done))
                    t.daemon = True
                    t.start()
        if kind == "drop_ack":
            return 504, {"error": "gateway_timeout"}     # stored, but the acknowledgement never arrives
        if kind == "wrong_ack_conversation":
            return 200, dict(ack, conversationId="other-" + cid)
        return 200, ack

    def _reply(self, cid, rid, text, done):
        with self.lock:
            for m in self.projects.get(cid, {}).get("messages", []):
                if m.get("id") == rid and m.get("role") == "assistant" and m.get("isStreaming"):
                    m["content"] = text if done else text[: len(text) // 2]
                    if done:
                        m["isStreaming"], m["jobStatus"] = False, "done"

    # ---------- HTTP server ----------
    def start(self, port=0):
        mock = self

        class H(BaseHTTPRequestHandler):
            def log_message(self, *a):
                pass

            def _go(self, method):
                u = urlsplit(self.path)
                body = None
                if method == "POST":
                    try:
                        n = int(self.headers.get("Content-Length", 0))
                        body = json.loads(self.rfile.read(n) or b"{}") if n <= 2_000_000 else None
                    except ValueError:
                        body = None
                code, obj = mock.handle(method, u.path, parse_qs(u.query), self.headers, body)
                d = json.dumps(obj).encode("utf-8")
                self.send_response(code)
                self.send_header("Content-Type", "application/json")
                self.send_header("Content-Length", str(len(d)))
                self.end_headers()
                self.wfile.write(d)

            def do_GET(self):
                self._go("GET")

            def do_POST(self):
                self._go("POST")

        self.server = ThreadingHTTPServer(("127.0.0.1", port), H)
        self.server.daemon_threads = True
        self.base_url = f"http://127.0.0.1:{self.server.server_address[1]}"
        threading.Thread(target=self.server.serve_forever, daemon=True).start()
        return self.base_url

    def stop(self):
        if self.server:
            self.server.shutdown()
            self.server.server_close()
            self.server = None
