"""Local HTTP endpoint (127.0.0.1 only) that the Cent bridge extension reports to.

Every POST must carry the managed profile ID (X-HBM-Tag) and that profile's own secret token (X-HBM-Auth),
generated by the Manager and written only into that profile's copy of the extension. Requests without a valid
pair are refused (no state is accepted and no command is handed out). The one exception lets an older bridge copy
of a KNOWN profile (no token yet) take a single "reload_ext" so it picks up the new files that carry its token."""
import hmac
import json
import queue
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

from .config import BRIDGE_PORT, log


class Bridge:
    def __init__(self):
        self.inbox = queue.Queue()          # authenticated reports for the UI thread
        self.commands = {}                  # profile tag -> [cmd]
        self.tokens = {}                    # profile tag -> secret token (set by the controller)
        self.picked = {}                    # dispatch id -> time its command was handed to the bridge
        self.lock = threading.Lock()
        self.server = None
        self.error = None
        self.ext_version = ""
        self._rej_logged = {}

    def set_tokens(self, tokens):
        with self.lock:
            self.tokens = dict(tokens)

    def queue_command(self, tag, cmd):
        with self.lock:
            self.commands.setdefault(tag or "", []).append(cmd)

    def drop_command(self, tag, pred):
        """Remove queued (not yet delivered) commands of a profile matching pred. Returns how many."""
        with self.lock:
            q = self.commands.get(tag or "") or []
            keep = [c for c in q if not pred(c)]
            self.commands[tag or ""] = keep
            return len(q) - len(keep)

    def _take(self, tag):
        with self.lock:
            cmds = self.commands.pop(tag or "", [])
            now = time.time()
            for c in cmds:
                if c.get("dispatch_id"):
                    self.picked[c["dispatch_id"]] = now
            return cmds

    def auth(self, tag, token):
        if not tag or not token:
            return False
        with self.lock:
            want = self.tokens.get(tag)
        return bool(want) and hmac.compare_digest(str(want), str(token))

    def known(self, tag):
        with self.lock:
            return tag in self.tokens

    def _reject_log(self, why, tag):
        k = (why, tag)
        if time.time() - self._rej_logged.get(k, 0) > 300:
            self._rej_logged[k] = time.time()
            log(f"bridge: refused request ({why}, tag={tag or '-'})")

    def start(self):
        bridge = self

        class H(BaseHTTPRequestHandler):
            def log_message(self, *a):
                pass

            def _reply(self, obj, code=200):
                d = json.dumps(obj).encode()
                self.send_response(code)
                self.send_header("Content-Type", "application/json")
                self.send_header("Content-Length", str(len(d)))
                self.end_headers()
                self.wfile.write(d)

            def do_GET(self):
                if self.path.startswith("/hbm-tag?"):
                    # first page of a new managed profile (or a pairing tab): the bridge reads the tag from this URL
                    if "close=1" in self.path:   # pairing: the bridge closes this tab itself
                        d = (b"<!doctype html><meta charset=utf-8><title>Hark Browser Manager</title>"
                             b"<body style='font:16px Segoe UI;padding:40px'>Hark Browser Manager: bridge pairing...</body>")
                    else:
                        d = (b"<!doctype html><meta charset=utf-8><meta http-equiv=refresh content='2;url=https://hark.com/'>"
                             b"<title>Hark Browser Manager</title><body style='font:18px Segoe UI;padding:40px'>"
                             b"Hark Browser Manager: profile ready. Opening Hark...</body>")
                    self.send_response(200)
                    self.send_header("Content-Type", "text/html; charset=utf-8")
                    self.send_header("Content-Length", str(len(d)))
                    self.end_headers()
                    self.wfile.write(d)
                    return
                if self.path.startswith("/ping"):
                    return self._reply({"app": "HarkBrowserManager", "ok": True})
                self._reply({"error": "not found"}, 404)

            def do_POST(self):
                # web pages are refused by their Origin; the per-profile token below is the real check
                origin = self.headers.get("Origin", "")
                if origin and not origin.startswith("chrome-extension://"):
                    return self._reply({"error": "forbidden"}, 403)
                try:
                    n = int(self.headers.get("Content-Length", 0))
                    if n > 2_000_000:
                        return self._reply({"error": "too large"}, 413)
                    body = json.loads(self.rfile.read(n) or b"{}")
                except Exception:
                    return self._reply({"error": "bad json"}, 400)
                if self.path != "/report":
                    return self._reply({"error": "not found"}, 404)
                tag = self.headers.get("X-HBM-Tag", "") or ""
                token = self.headers.get("X-HBM-Auth", "") or ""
                if not bridge.auth(tag, token):
                    btag = str(body.get("tag") or "")
                    # an older bridge copy (no token) of one of OUR profiles: let it reload to the new files once
                    if not token and bridge.known(btag) and body.get("ver") and body.get("ver") != bridge.ext_version:
                        bridge._reject_log("unauthenticated old bridge " + str(body.get("ver")) + ", reload sent", btag)
                        return self._reply({"commands": [{"type": "reload_ext"}]}, 401)
                    bridge._reject_log("bad or missing token", tag or btag)
                    return self._reply({"error": "unauthorized"}, 401)
                if body.get("tag") and body.get("tag") != tag:
                    bridge._reject_log("tag mismatch", tag)
                    return self._reply({"error": "unauthorized"}, 401)
                body["tag"] = tag            # the authenticated profile ID, never what the body claims
                body["_auth"] = True
                body["_t"] = time.time()
                bridge.inbox.put(body)
                return self._reply({"commands": bridge._take(tag)})

        try:
            self.server = ThreadingHTTPServer(("127.0.0.1", BRIDGE_PORT), H)
        except OSError as e:
            self.error = str(e)
            log(f"bridge bind failed: {e}")
            return False
        threading.Thread(target=self.server.serve_forever, daemon=True).start()
        log(f"bridge listening on {BRIDGE_PORT} (per-profile token auth)")
        return True

    def stop(self):
        if self.server:
            self.server.shutdown()
